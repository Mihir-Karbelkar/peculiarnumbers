export type SieveAlgorithmId = 'eratosthenes' | 'linear' | 'sundaram' | 'lucky';

export type SieveAlgorithmMeta = {
  id: SieveAlgorithmId;
  name: string;
  shortName: string;
  description: string;
  complexity: string;
  resultLabel: string;
  bestFor: string;
  pseudocode: string[];
};

export type SieveFrame = {
  phase: string;
  title: string;
  detail: string;
  formula?: string;
  active: number[];
  touched: number[];
  eliminated: boolean[];
  results: boolean[];
  owner: number[];
  inspections: number;
  writes: number;
  revisits: number;
};

export type SieveRun = {
  algorithm: SieveAlgorithmId;
  limit: number;
  frames: SieveFrame[];
  values: number[];
  resultLabel: string;
};

